// Environment check for Drift (npm run doctor). Exits 1 if a required check fails.
// Prints only whether env vars are set, never their values.
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const exists = (rel) => fs.existsSync(path.join(root, rel))
const isSet = (name) => Boolean(process.env[name])
const ok = (msg) => console.log(`✓ ${msg}`)
const warn = (msg) => console.log(`! ${msg}`)
let failed = false
const fail = (msg) => {
  failed = true
  console.log(`✗ ${msg}`)
}

// Required: Node.js >= 20
const nodeMajor = Number(process.versions.node.split('.')[0])
if (nodeMajor >= 20) ok(`Node.js ${process.version} (>= 20)`)
else fail(`Node.js ${process.version} is too old, need >= 20`)

// Required: installed Electron matches devDependencies.electron
const wanted = pkg.devDependencies.electron.replace(/^[\^~]/, '')
const electronPkg = 'node_modules/electron/package.json'
if (!exists(electronPkg)) {
  fail('electron is not installed, run npm install')
} else {
  const installed = JSON.parse(fs.readFileSync(path.join(root, electronPkg), 'utf8')).version
  if (installed === wanted) ok(`electron ${installed} matches package.json`)
  else fail(`electron ${installed} installed, package.json wants ${wanted}, run npm install`)
}

// Required: electron-builder installed
if (exists('node_modules/electron-builder')) ok('electron-builder installed')
else fail('electron-builder is not installed, run npm install')

// Required: bundled preload exists (generated by prestart)
if (exists('src/preload/ui-main.js')) ok('src/preload/ui-main.js present')
else fail('src/preload/ui-main.js missing, run npm run prestart')

// Required: entry point and error page
for (const rel of ['src/main/main.js', 'src/ui/index.html', 'src/web/error.html']) {
  if (exists(rel)) ok(`${rel} present`)
  else fail(`${rel} missing`)
}

// Warning only: signing and notarization variables for macOS releases
for (const name of ['MAC_CERT', 'MAC_CERT_PASSWORD', 'APPLE_ID', 'APPLE_APP_SPECIFIC_PASSWORD', 'APPLE_TEAM_ID']) {
  const line = `${name}: ${isSet(name) ? 'set' : 'not set'}`
  if (isSet(name)) ok(line)
  else warn(line)
}

// Warning only: proxy variables
const proxySet = isSet('HTTPS_PROXY') || isSet('HTTP_PROXY')
const proxyLine = `HTTPS_PROXY or HTTP_PROXY: ${proxySet ? 'set' : 'not set'}`
if (proxySet) ok(proxyLine)
else warn(proxyLine)

process.exitCode = failed ? 1 : 0
